const { chromium } = require('playwright');
const { execSync } = require('child_process');
const path = require('path');
const BASE = 'http://localhost:3000';
const check = (name, ok, info = '') => console.log((ok ? 'PASS' : 'FAIL') + '  ' + name + (info ? '  — ' + info : ''));
const sql = (q) => execSync(`docker exec -i supabase_db_pbs-go psql -U postgres -d postgres -Atq`, { input: q }).toString().trim();
const MAYA = '00000000-0000-0000-0000-0000000000a5';
const go = (p, u) => p.goto(BASE + u, { waitUntil: 'networkidle' });
async function signIn(browser, name) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 850 } }); const p = await ctx.newPage();
  await go(p, '/login'); await p.locator('.lp-demo button', { hasText: name }).click();
  await p.waitForURL('**/home'); await p.waitForLoadState('networkidle'); return { ctx, p };
}
const loaded = (p, sel) => p.locator(sel).first().evaluate((i) => new Promise((r) => (i.complete ? r(i.naturalWidth > 0) : (i.onload = () => r(true), i.onerror = () => r(false)))));
(async () => {
  const browser = await chromium.launch();
  sql(`update public.profiles set photo_path = null, avatar = 'a09', avatar_icon = 'a09' where id = '${MAYA}'`);
  const maya = await signIn(browser, 'Maya Odeh');
  const p = maya.p;
  check('Before: the top bar shows the illustrated avatar', /avatars\/f09\.png/.test(await p.locator('header img').first().getAttribute('src').catch(() => '')) || (await p.locator('img[src*="/avatars/f09.png"]').count()) > 0);
  await go(p, '/profile/edit');
  await p.locator('[data-change-photo]').click();
  await p.locator('[data-photo-input]').setInputFiles(path.join(__dirname, 'proof.png'));
  await p.locator('[data-save-photo]').click();
  await p.waitForFunction(() => /Saved/.test(document.body.innerText), null, { timeout: 20000 });
  await p.waitForTimeout(800);
  const avatar = sql(`select avatar from public.profiles where id = '${MAYA}'`);
  check('Uploading a photo changes the stored avatar', /^u:/.test(avatar), avatar);
  await go(p, '/home');
  const src = await p.locator(`img[src*="/api/avatar/${MAYA}"]`).first().getAttribute('src');
  check('The top bar now shows the photo', !!src, src || '');
  check('The photo really loads', await loaded(p, `img[src*="/api/avatar/${MAYA}"]`));
  const other = await signIn(browser, 'Yousef Saleh');
  await go(other.p, '/people');
  check('Other students see the photo too', (await other.p.locator(`img[src*="/api/avatar/${MAYA}"]`).count()) > 0);
  const status = await other.p.evaluate(async (id) => (await fetch(`/api/avatar/${id}`)).status, MAYA);
  check('The photo link works for signed-in classmates', status === 200, String(status));
  const anon = await (await browser.newContext()).newPage();
  const r = await anon.goto(`${BASE}/api/avatar/${MAYA}`);
  check('It is not available when signed out', r.status() === 401 || /\/login/.test(anon.url()), String(r.status()));
  await go(p, '/profile/edit');
  await p.locator('[data-change-photo]').click();
  await p.locator('[data-remove-photo]').click();
  await p.locator('[data-save-photo]').click();
  await p.waitForFunction(() => /Saved/.test(document.body.innerText), null, { timeout: 20000 });
  await p.waitForTimeout(800);
  check('Removing the photo brings the illustrated avatar back', sql(`select avatar from public.profiles where id = '${MAYA}'`) === 'a09');
  await go(p, '/home');
  check('The top bar shows the illustration again', (await p.locator('img[src*="/avatars/f09.png"]').count()) > 0);
  await browser.close();
})();
