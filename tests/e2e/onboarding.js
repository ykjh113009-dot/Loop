const text = async (p) => (await p.locator('body').innerText()).replace(/\s+/g, ' ');
const reset = (id) => sql(`update public.profiles set onboarded_at = null, section = null, avatar = 'a01', avatar_icon = 'a01', photo_path = null, bio = '' where id = '${id}'; delete from public.profile_interests where profile_id = '${id}'; delete from public.rate_events;`);
async function signIn(b, name, vp) {
  const ctx = await b.newContext({ viewport: vp }); const p = await ctx.newPage();
  await go(p, '/login'); await p.locator('.lp-demo button', { hasText: name }).click();
  await p.waitForURL(/\/(welcome|home)/, { timeout: 20000 }); await p.waitForLoadState('networkidle');
  if (/\/home/.test(p.url())) await p.waitForURL('**/welcome', { timeout: 4000 }).catch(() => {});
  await p.waitForLoadState('networkidle'); return { ctx, p };
}
